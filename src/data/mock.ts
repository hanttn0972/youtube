const makeStages = (upTo: number, failAt?: number): Stage[] => {
  const defs: { id: Stage['id']; label: string; engine: string }[] = [
    { id: 'download', label: 'Download', engine: 'yt-dlp' },
    { id: 'ocr', label: 'OCR', engine: 'PaddleOCR' },
    { id: 'transcript', label: 'Transcript', engine: 'Whisper v3' },
    { id: 'translation', label: 'Translation', engine: 'Gemini Flash' },
    { id: 'tts', label: 'TTS', engine: 'VietTTS' },
    { id: 'audio_mix', label: 'Audio Mix', engine: 'FFmpeg' },
    { id: 'render', label: 'Render', engine: 'FFmpeg' },
    { id: 'subtitle', label: 'Subtitle', engine: 'ASS Renderer' },
  ];
  return defs.map((d, i) => ({
    id: d.id,
    label: d.label,
    engine: d.engine,
    target: i >= 2 && i <= 4 ? 'remote' : 'local',
    enabled: true,
    status:
      failAt !== undefined && i === failAt
        ? 'failed'
        : i < upTo
        ? 'completed'
        : i === upTo
        ? (failAt !== undefined ? 'failed' : 'running')
        : 'pending',
    startTime: i < upTo ? `2026-09-20T0${8 + i}:00:00Z` : undefined,
    duration: i < upTo ? `${2 + i * 3}m ${10 + i * 7}s` : undefined,
    logs:
      i <= upTo
        ? [
            `[INFO] Starting ${d.label}...`,
            `[INFO] Engine: ${d.engine}`,
            `[INFO] Processing input...`,
            i < upTo ? `[INFO] Completed successfully.` : `[INFO] In progress...`,
          ]
        : [],
    errorMessage:
      failAt !== undefined && i === failAt
        ? 'CUDA out of memory: tried to allocate 2.50 GiB (GPU 0; 8.00 GiB total capacity)'
        : undefined,
  }));
};

